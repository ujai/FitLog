import { fmtDate } from "@/lib/format";

/** The row as stored: `pointers` is a json column, so its shape is narrowed here. */
type ReviewRow = {
  summary: string;
  model: string;
  createdAt: Date;
  pointers: unknown;
};

/**
 * The AI's read on someone's whole scan history.
 *
 * Split out of the scans route, which was five reads, chart shaping and two
 * AI-review presentations in one file. This half owns the pointers' shape, which
 * comes out of the database as json and has to be narrowed before it is rendered.
 */
export function ProgressReview({ review, name }: { review: ReviewRow; name: string }) {
  const pointers = (review.pointers ?? {}) as {
    positives?: string[];
    focus?: Array<{ area: string; observation: string; suggestion: string }>;
  };

  return (
    <section
      id="progress-review"
      tabIndex={-1}
      className="rounded-2xl border border-emerald-200 bg-emerald-50/70 p-5 outline-none"
    >
      <h2 className="mb-2 font-medium">✨ AI review — {name}</h2>
      <p className="max-w-prose text-sm leading-relaxed text-stone-600">{review.summary}</p>
      {pointers.positives?.length ? (
        <div className="mt-4">
          <h3 className="text-sm font-medium text-emerald-700">Going well</h3>
          <ul className="mt-1 max-w-prose list-inside list-disc text-sm text-stone-600">
            {pointers.positives.map((p, i) => (
              <li key={i}>{p}</li>
            ))}
          </ul>
        </div>
      ) : null}
      {pointers.focus?.length ? (
        <div className="mt-4 space-y-3">
          <h3 className="text-sm font-medium text-amber-700">Where to improve</h3>
          {pointers.focus.map((f, i) => (
            <div key={i} className="rounded-xl border border-stone-200 bg-white/70 p-4">
              <p className="font-medium">{f.area}</p>
              <p className="mt-1 max-w-prose text-sm text-stone-600">{f.observation}</p>
              <p className="mt-1.5 max-w-prose text-sm text-emerald-700">→ {f.suggestion}</p>
            </div>
          ))}
        </div>
      ) : null}
      <p className="mt-4 text-xs text-stone-600">
        Generated by {review.model} on {fmtDate(review.createdAt)}. AI output is
        informational — not medical advice.
      </p>
    </section>
  );
}
